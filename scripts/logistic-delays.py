import numpy as np
import pandas as pd

# We reuse:
# - best_model
# - best_model_name
# - scaler
# - X (for feature order)
# - q75 (Demand_Surprise threshold for Big_Surprise)

# Identify traffic dummy columns from training data
traffic_dummy_cols = [col for col in X.columns if col.startswith("Traffic_Status_")]

def predict_delay(
    asset_utilization,
    inventory_level,
    waiting_time,
    temperature,
    user_transaction_amount,
    demand_forecast,
    traffic_status   # 'Clear', 'Detour', or 'Heavy'
):
    """
    Predict delay probability for a single logistics transaction.
    Returns: (probability_of_delay, predicted_label)
    """

    # -----------------------------
    # 1) Recreate engineered features (match training pipeline!)
    # -----------------------------
    demand_surprise = user_transaction_amount - demand_forecast
    high_util = 1 if asset_utilization > 85 else 0
    big_surprise = 1 if demand_surprise > q75 else 0   # same Q75 as training
    interaction = high_util * big_surprise
    waiting_log = np.log1p(waiting_time)
    temp_high = 1 if temperature > 25 else 0
    utilization_waiting = asset_utilization * waiting_log
    surprise_inventory = demand_surprise * inventory_level

    row = {
        'High_Utilization': high_util,
        'Big_Surprise': big_surprise,
        'Interaction': interaction,
        'Asset_Utilization': asset_utilization,
        'Demand_Surprise': demand_surprise,
        'Waiting_Time_Log': waiting_log,
        'Inventory_Level': inventory_level,
        'Temperature_High': temp_high,
        'Utilization_Waiting': utilization_waiting,
        'Surprise_Inventory': surprise_inventory
    }

    # -----------------------------
    # 2) Add traffic dummy columns
    # -----------------------------
    # Initialise all dummy columns to 0
    for col in traffic_dummy_cols:
        row[col] = 0

    # Normalise traffic status text
    traffic_status = traffic_status.strip().title()

    # Encode based on how one-hot encoding was done (drop_first=True)
    # Base category is "Clear" (both dummy = 0)
    if traffic_status == "Detour" and 'Traffic_Status_Detour' in traffic_dummy_cols:
        row['Traffic_Status_Detour'] = 1
    elif traffic_status == "Heavy" and 'Traffic_Status_Heavy' in traffic_dummy_cols:
        row['Traffic_Status_Heavy'] = 1
    # If 'Clear' or unrecognised, both stay 0

    # -----------------------------
    # 3) Create DataFrame in correct column order
    # -----------------------------
    input_df = pd.DataFrame([row])
    input_df = input_df.reindex(columns=X.columns, fill_value=0)

    # -----------------------------
    # 4) Scale if needed and predict
    # -----------------------------
    if best_model_name == "Logistic Regression":
        input_scaled = scaler.transform(input_df)
        delay_prob = best_model.predict_proba(input_scaled)[0, 1]
    else:
        delay_prob = best_model.predict_proba(input_df)[0, 1]

    label = "Delay" if delay_prob >= 0.5 else "No Delay"

    return delay_prob, label


def run_interactive_prediction():
    """
    Simple CLI-style interaction in Colab:
    Asks user for inputs, then prints model prediction.
    """
    print("====================================")
    print("   Logistics Delay Prediction Tool  ")
    print("====================================")
    print("Enter shipment details within the suggested ranges.")
    print("Type 'q' at any prompt to quit.\n")

    while True:
        try:
            # Asset utilization (e.g., 0–100 %)
            val = input("Asset Utilization (%) [0–100] (or 'q' to quit): ")
            if val.lower() == 'q':
                break
            asset_utilization = float(val)

            # Inventory level
            val = input("Inventory Level (e.g., 0–600): ")
            if val.lower() == 'q':
                break
            inventory_level = float(val)

            # Waiting time
            val = input("Waiting Time (minutes) [0–120]: ")
            if val.lower() == 'q':
                break
            waiting_time = float(val)

            # Temperature
            val = input("Temperature (°C) [0–50]: ")
            if val.lower() == 'q':
                break
            temperature = float(val)

            # Demand forecast and actual quantity
            val = input("Demand Forecast (units) [0–600]: ")
            if val.lower() == 'q':
                break
            demand_forecast = float(val)

            val = input("User Transaction Amount (actual units) [0–600]: ")
            if val.lower() == 'q':
                break
            user_transaction_amount = float(val)

            # Traffic status
            val = input("Traffic Status ['Clear', 'Detour', 'Heavy']: ")
            if val.lower() == 'q':
                break
            traffic_status = val

            # -----------------------------
            # Call prediction function
            # -----------------------------
            prob, label = predict_delay(
                asset_utilization=asset_utilization,
                inventory_level=inventory_level,
                waiting_time=waiting_time,
                temperature=temperature,
                user_transaction_amount=user_transaction_amount,
                demand_forecast=demand_forecast,
                traffic_status=traffic_status
            )

            print("\n========== PREDICTION RESULT ==========")
            print(f"Predicted delay probability: {prob:.3f}")
            print(f"Predicted label: {label}")
            print("=======================================\n")

        except ValueError:
            print("⚠ Invalid numeric input. Please enter numbers only.\n")
        except Exception as e:
            print(f"⚠ Error: {e}")
            break

    print("Exiting prediction tool.")


