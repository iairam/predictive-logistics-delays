sns.set_style("darkgrid")
np.random.seed(42)

# -------------------------
# Load dataset
# -------------------------
df = pd.read_csv("/content/smart_logistics_dataset.csv")

# -------------------------
# Feature engineering
# -------------------------
# Asset_Utilization is in percentage-like values (e.g., 60, 80, 99), so use 85 as threshold
df['High_Utilization'] = (df['Asset_Utilization'] > 85).astype(int)

# Demand surprise: actual - forecast
df['Demand_Surprise'] = df['User_Transaction_Amount'] - df['Demand_Forecast']

# Top 25% of demand surprise as "big surprise"
q75 = df['Demand_Surprise'].quantile(0.75)
df['Big_Surprise'] = (df['Demand_Surprise'] > q75).astype(int)

# Interaction of high utilization and big surprise
df['Interaction'] = df['High_Utilization'] * df['Big_Surprise']

# Log of waiting time to reduce skew
df['Waiting_Time_Log'] = np.log1p(df['Waiting_Time'])

# High temperature flag
df['Temperature_High'] = (df['Temperature'] > 25).astype(int)

# Extra interaction features
df['Utilization_Waiting'] = df['Asset_Utilization'] * df['Waiting_Time_Log']
df['Surprise_Inventory'] = df['Demand_Surprise'] * df['Inventory_Level']

# One-hot encode Traffic_Status (safe to use, no leakage)
df_encoded = pd.get_dummies(df[['Traffic_Status']], drop_first=True)

# -------------------------
# Feature matrix and target
# -------------------------
base_features = [
    'High_Utilization',
    'Big_Surprise',
    'Interaction',
    'Asset_Utilization',
    'Demand_Surprise',
    'Waiting_Time_Log',
    'Inventory_Level',
    'Temperature_High',
    'Utilization_Waiting',
    'Surprise_Inventory'
]

X = pd.concat([df[base_features], df_encoded], axis=1)
y = df['Logistics_Delay']

print("Final feature columns:", X.columns.tolist())

# -------------------------
# Train/Validation/Test split
# -------------------------
X_trainval, X_test, y_trainval, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42
)

X_train, X_val, y_train, y_val = train_test_split(
    X_trainval, y_trainval, test_size=0.25, stratify=y_trainval, random_state=42
)
# Now: 60% train, 20% validation, 20% test

print("Train shape:", X_train.shape)
print("Validation shape:", X_val.shape)
print("Test shape:", X_test.shape)

# -------------------------
# Handle class imbalance with SMOTE (train only)
# -------------------------
smote = SMOTE(random_state=42)
X_train_res, y_train_res = smote.fit_resample(X_train, y_train)

print("\nClass balance before SMOTE:", y_train.value_counts(normalize=True))
print("Class balance after SMOTE:", y_train_res.value_counts(normalize=True))

# -------------------------
# Scale features (for Logistic Regression only)
# -------------------------
scaler = StandardScaler()
X_train_res_scaled = scaler.fit_transform(X_train_res)
X_val_scaled = scaler.transform(X_val)
X_test_scaled = scaler.transform(X_test)

# -------------------------
# Define models
# -------------------------
models = {
    "Logistic Regression": LogisticRegression(max_iter=2000, random_state=42),
    "Random Forest": RandomForestClassifier(n_estimators=300, random_state=42),
    "XGBoost": XGBClassifier(
        n_estimators=300,
        learning_rate=0.05,
        max_depth=5,
        subsample=0.8,
        colsample_bytree=0.8,
        random_state=42,
        eval_metric='logloss'
    )
}

# -------------------------
# Train and evaluate on validation set
# -------------------------
metrics_val = {}

for name, model in models.items():
    if name == "Logistic Regression":
        model.fit(X_train_res_scaled, y_train_res)
        y_val_pred = model.predict(X_val_scaled)
        y_val_proba = model.predict_proba(X_val_scaled)[:, 1]
    else:
        model.fit(X_train_res, y_train_res)
        y_val_pred = model.predict(X_val)
        y_val_proba = model.predict_proba(X_val)[:, 1]

    metrics_val[name] = {
        "AUC_val": roc_auc_score(y_val, y_val_proba),
        "F1_val": f1_score(y_val, y_val_pred)
    }

print("\nValidation Results")
print(pd.DataFrame(metrics_val).T)

# -------------------------
# Select best model based on validation (AUC, then F1)
# -------------------------
best_model_name = sorted(
    metrics_val.keys(),
    key=lambda k: (metrics_val[k]['AUC_val'], metrics_val[k]['F1_val']),
    reverse=True
)[0]
best_model = models[best_model_name]

